-- TECHNET - CONSULTIVO: core tracking model and read scopes.
-- Ingestion and privileged mutations are performed by Edge Functions using service role.

create table if not exists public.tv_consultivo_devices (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  install_id text not null,
  token_hash text not null unique,
  device_name text,
  platform text not null default 'android'
    check (platform in ('android','ios')),
  app_version text,
  active boolean not null default true,
  last_seen_at timestamptz,
  last_battery numeric(5,2)
    check (last_battery is null or (last_battery between 0 and 100)),
  last_network_type text,
  created_at timestamptz not null default now(),
  revoked_at timestamptz,
  unique (user_id, install_id),
  check (length(token_hash) >= 32)
);

create table if not exists public.tv_consultivo_team_schedules (
  id uuid primary key default gen_random_uuid(),
  team_id uuid not null references public.tv_teams(id) on delete cascade,
  weekday smallint not null check (weekday between 0 and 6),
  starts_at time not null,
  ends_at time not null,
  timezone text not null default 'America/Fortaleza',
  active boolean not null default true,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique (team_id, weekday)
);

create table if not exists public.tv_consultivo_positions (
  id bigint generated by default as identity primary key,
  source_id uuid not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  team_id uuid references public.tv_teams(id) on delete set null,
  device_id uuid not null references public.tv_consultivo_devices(id) on delete restrict,
  recorded_at timestamptz not null,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy real check (accuracy is null or accuracy >= 0),
  speed real check (speed is null or speed >= 0),
  heading real check (heading is null or (heading >= 0 and heading < 360)),
  battery_level numeric(5,2)
    check (battery_level is null or (battery_level between 0 and 100)),
  activity_type text,
  activity_confidence smallint
    check (activity_confidence is null or activity_confidence between 0 and 100),
  provider text,
  metadata jsonb not null default '{}'::jsonb
    check (jsonb_typeof(metadata)='object'),
  created_at timestamptz not null default now()
);

create table if not exists public.tv_consultivo_pauses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  team_id uuid references public.tv_teams(id) on delete set null,
  device_id uuid not null references public.tv_consultivo_devices(id) on delete restrict,
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  reason text,
  created_at timestamptz not null default now(),
  check (ended_at is null or ended_at >= started_at)
);

create table if not exists public.tv_consultivo_daily_summaries (
  day date not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  team_id uuid references public.tv_teams(id) on delete set null,
  distance_meters numeric(14,2) not null default 0 check (distance_meters >= 0),
  movement_seconds integer not null default 0 check (movement_seconds >= 0),
  stopped_seconds integer not null default 0 check (stopped_seconds >= 0),
  first_position_at timestamptz,
  last_position_at timestamptz,
  position_count integer not null default 0 check (position_count >= 0),
  gps_quality text,
  computed_at timestamptz not null default now(),
  primary key (day, user_id)
);

create table if not exists public.tv_consultivo_web_bridges (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  device_id uuid not null references public.tv_consultivo_devices(id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  consumed_at timestamptz,
  created_at timestamptz not null default now(),
  check (length(token_hash) >= 32)
);

create index if not exists idx_consultivo_devices_user_active
  on public.tv_consultivo_devices(user_id, active);
create index if not exists idx_consultivo_positions_user_recorded
  on public.tv_consultivo_positions(user_id, recorded_at desc);
create index if not exists idx_consultivo_positions_team_recorded
  on public.tv_consultivo_positions(team_id, recorded_at desc);
create index if not exists idx_consultivo_positions_device_recorded
  on public.tv_consultivo_positions(device_id, recorded_at desc);
create index if not exists idx_consultivo_pauses_user_started
  on public.tv_consultivo_pauses(user_id, started_at desc);
create unique index if not exists idx_consultivo_open_pause_user
  on public.tv_consultivo_pauses(user_id)
  where ended_at is null;
create index if not exists idx_consultivo_summaries_team_day
  on public.tv_consultivo_daily_summaries(team_id, day desc);
create index if not exists idx_consultivo_bridges_expiry
  on public.tv_consultivo_web_bridges(expires_at)
  where consumed_at is null;

alter table public.tv_consultivo_devices enable row level security;
alter table public.tv_consultivo_team_schedules enable row level security;
alter table public.tv_consultivo_positions enable row level security;
alter table public.tv_consultivo_pauses enable row level security;
alter table public.tv_consultivo_daily_summaries enable row level security;
alter table public.tv_consultivo_web_bridges enable row level security;

drop policy if exists consultivo_devices_read on public.tv_consultivo_devices;
create policy consultivo_devices_read on public.tv_consultivo_devices
for select to authenticated
using (
  user_id=auth.uid()
  or public.tv_current_role()='admin'
  or (
    public.tv_current_role()='supervisor'
    and exists (
      select 1 from public.tv_profiles p
      where p.user_id=tv_consultivo_devices.user_id
        and p.active=true
        and p.team_id=public.tv_current_team()
    )
  )
);

drop policy if exists consultivo_schedules_read on public.tv_consultivo_team_schedules;
create policy consultivo_schedules_read on public.tv_consultivo_team_schedules
for select to authenticated
using (
  public.tv_current_role()='admin'
  or team_id=public.tv_current_team()
);

drop policy if exists consultivo_positions_read on public.tv_consultivo_positions;
create policy consultivo_positions_read on public.tv_consultivo_positions
for select to authenticated
using (
  user_id=auth.uid()
  or public.tv_current_role()='admin'
  or (
    public.tv_current_role()='supervisor'
    and team_id=public.tv_current_team()
  )
);

drop policy if exists consultivo_pauses_read on public.tv_consultivo_pauses;
create policy consultivo_pauses_read on public.tv_consultivo_pauses
for select to authenticated
using (
  user_id=auth.uid()
  or public.tv_current_role()='admin'
  or (
    public.tv_current_role()='supervisor'
    and team_id=public.tv_current_team()
  )
);

drop policy if exists consultivo_summaries_read on public.tv_consultivo_daily_summaries;
create policy consultivo_summaries_read on public.tv_consultivo_daily_summaries
for select to authenticated
using (
  user_id=auth.uid()
  or public.tv_current_role()='admin'
  or (
    public.tv_current_role()='supervisor'
    and team_id=public.tv_current_team()
  )
);

drop policy if exists consultivo_bridges_read_own on public.tv_consultivo_web_bridges;
create policy consultivo_bridges_read_own on public.tv_consultivo_web_bridges
for select to authenticated
using (user_id=auth.uid());

